#!/usr/bin/env node
// Regenerates apps/web/src/lib/stress-lab-data.ts from three committed files, unchanged:
//   data/cases/duplicate-charge-eval.v1.json        pinned 30-case dataset (inputs, ground truth)
//   evals/results/duplicate-charge-eval.v1.json     fixture benchmark (JARVIS outcome and stop reasons)
//   evals/results/baseline-no-policy.fixture.json   offline no-policy comparison (same proposals, policy removed)
// apps/web/test/stress-lab.test.ts rebuilds the same rows from the files and fails on any difference.
//   node scripts/build-stress-lab-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { buildStressLabRows } from "../apps/web/src/lib/stress-lab-join.ts";

const load = (p) => JSON.parse(readFileSync(new URL(`../${p}`, import.meta.url), "utf8"));
const rows = buildStressLabRows(
  load("data/cases/duplicate-charge-eval.v1.json"),
  load("evals/results/duplicate-charge-eval.v1.json"),
  load("evals/results/baseline-no-policy.fixture.json"),
);
const out = `// GENERATED by scripts/build-stress-lab-data.mjs from committed evidence. Do not edit by hand.
// Checked against the source files by apps/web/test/stress-lab.test.ts.
import type { StressLabRow } from "./stress-lab-join.ts";

export const STRESS_LAB_ROWS: StressLabRow[] = ${JSON.stringify(rows, null, 1)};
`;
writeFileSync(new URL("../apps/web/src/lib/stress-lab-data.ts", import.meta.url), out);
console.log(`${rows.length} cases written`);
