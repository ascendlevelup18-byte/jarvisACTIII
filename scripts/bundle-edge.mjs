// Bundles supabase/functions/jarvis-gateway into one readable ESM file for deployment through tools that
// upload single files. zod and supabase-js stay external and resolve through the function's deno.json.
// Output: supabase/functions/jarvis-gateway/dist/index.ts (generated; rebuild after any shared change).
import { execFileSync } from "node:child_process";
import { mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
execFileSync(process.execPath, [join(root, "scripts/sync-edge-shared.mjs")], { stdio: "inherit" });
const require = createRequire(join(root, "apps/web/package.json"));
const { build } = await import(pathToFileURL(require.resolve("rolldown")).href);
const outDir = join(root, "supabase/functions/jarvis-gateway/dist");
mkdirSync(outDir, { recursive: true });
await build({
  input: join(root, "supabase/functions/jarvis-gateway/index.ts"),
  external: ["zod", "@supabase/supabase-js"],
  platform: "neutral",
  output: { file: join(outDir, "index.ts"), format: "esm", comments: false, minify: { compress: false, mangle: false, codegen: { removeWhitespace: true } }, banner: "// GENERATED by scripts/bundle-edge.mjs from supabase/functions. Do not edit.\n// deno-lint-ignore-file" },
});
console.log("bundled", join(outDir, "index.ts"));
